"""
FAQ 및 약관 테이블 초기 데이터 삽입
- faq_categories, faq_items: 기존 하드코딩 FAQ 데이터
- legal_documents: 개인정보처리방침, 이용약관
"""
from app.database import SessionLocal
from app import models


def run_migration(db):
    # Legal documents (개인정보처리방침, 이용약관)
    for doc_type in ("privacy", "terms"):
        if db.query(models.LegalDocument).filter(models.LegalDocument.doc_type == doc_type).first():
            continue
        content = ""
        if doc_type == "privacy":
            content = """플로우 개인정보 보호정책

1. 수집하는 개인정보 항목
회사는 서비스 제공을 위해 다음과 같은 개인정보를 수집합니다.
- 필수항목: 이메일 주소, 비밀번호, 닉네임
- 선택항목: 프로필 이미지

2. 개인정보의 수집 및 이용 목적
- 회원 가입 및 관리: 회원제 서비스 이용에 따른 본인확인, 개인식별, 불량회원의 부정이용 방지
- 서비스 제공: 주식 정보 제공, 포트폴리오 관리, 투자 리포트 제공
- 마케팅 및 광고: 이벤트 및 광고성 정보 제공 (동의 시)

3. 개인정보의 보유 및 이용기간
회원 탈퇴 시까지 보유하며, 탈퇴 후 즉시 파기합니다.
단, 관련 법령에 의해 보존할 필요가 있는 경우 해당 기간 동안 보존합니다.
- 계약 또는 청약철회 등에 관한 기록: 5년
- 소비자의 불만 또는 분쟁처리에 관한 기록: 3년
- 접속에 관한 기록: 1년

4. 개인정보의 제3자 제공
회사는 원칙적으로 이용자의 개인정보를 외부에 제공하지 않습니다.

5. 이용자의 권리
이용자는 언제든지 자신의 개인정보를 조회하거나 수정할 수 있으며, 회원 탈퇴를 통해 개인정보 처리 정지를 요청할 수 있습니다."""
        elif doc_type == "terms":
            content = """플로우 이용약관

제1조 (목적)
이 약관은 플로우(이하 "회사")가 제공하는 주식 정보 서비스(이하 "서비스")의 이용에 관한 조건 및 절차를 규정합니다.

제2조 (정의)
1. "서비스"란 회사가 제공하는 주식 정보 조회, 포트폴리오 관리 등의 서비스를 의미합니다.
2. "회원"이란 회사와 서비스 이용 계약을 체결한 자를 의미합니다.

제3조 (약관의 효력 및 변경)
1. 이 약관은 서비스를 이용하고자 하는 모든 회원에게 적용됩니다.
2. 회사는 필요한 경우 약관을 변경할 수 있으며, 변경된 약관은 서비스 내 공지사항을 통해 공지합니다.

제4조 (회원가입)
1. 이용자는 회사가 정한 양식에 따라 회원 정보를 기입한 후 약관에 동의함으로써 회원가입을 신청합니다.

제5조 (서비스 이용)
1. 서비스는 회원가입 완료 후 이용 가능합니다.
2. 서비스에서 제공하는 주식 정보는 참고 목적이며, 투자 판단의 최종 책임은 회원 본인에게 있습니다.

제6조 (회원 탈퇴 및 이용 제한)
1. 회원은 언제든지 서비스 내 설정을 통해 탈퇴를 요청할 수 있습니다."""

        doc = models.LegalDocument(doc_type=doc_type, content=content)
        db.add(doc)

    # FAQ 초기 데이터
    if db.query(models.FaqCategory).count() > 0:
        db.commit()
        return

    faq_data = [
        ("계정", [
            ("회원가입은 어떻게 하나요?", "앱 첫 화면에서 '회원가입' 버튼을 클릭하고, 이메일과 비밀번호를 입력하면 가입이 완료됩니다. 카카오, 네이버, 구글 소셜 계정으로도 간편하게 가입할 수 있습니다."),
            ("비밀번호를 잊어버렸어요.", "로그인 화면에서 '비밀번호 찾기'를 클릭하면 가입한 이메일로 비밀번호 재설정 링크가 발송됩니다. 메일함을 확인해주세요."),
            ("회원 탈퇴는 어떻게 하나요?", "설정 > 내 정보 > 회원 탈퇴 메뉴에서 탈퇴할 수 있습니다. 탈퇴 시 모든 데이터가 삭제되며 복구할 수 없으니 신중하게 결정해주세요."),
        ]),
        ("주식 정보", [
            ("주가 정보는 실시간인가요?", "주가 정보는 약 15~20분 지연된 데이터입니다. 실시간 시세는 증권사 앱을 참고해주세요."),
            ("관심 종목은 몇 개까지 등록할 수 있나요?", "관심 종목은 최대 50개까지 등록할 수 있습니다. 설정에서 관심 종목 목록을 관리할 수 있습니다."),
            ("주식 용어가 어려워요.", "홈 화면 하단의 '주식 용어 사전'에서 초보 투자자를 위한 용어 설명을 확인할 수 있습니다."),
        ]),
        ("알림", [
            ("알림이 오지 않아요.", "설정 > 알림 설정에서 푸시 알림이 켜져 있는지 확인해주세요. 기기의 시스템 설정에서 플로우 앱의 알림 권한이 허용되어 있는지 확인해주세요."),
            ("일정 알림은 무엇인가요?", "배당금 지급일, 실적 발표일 등 투자와 관련된 주요 일정을 미리 알려주는 기능입니다."),
        ]),
        ("기타", [
            ("간편 비밀번호 설정은 어떻게 하나요?", "설정 > 앱 설정 > 간편 비밀번호 설정에서 4~6자리 숫자로 간편 비밀번호를 설정할 수 있습니다."),
            ("앱에서 오류가 발생해요.", "앱을 최신 버전으로 업데이트 해주세요. 문제가 계속되면 고객센터로 문의해주세요."),
        ]),
    ]

    for order_idx, (cat_title, items) in enumerate(faq_data):
        cat = models.FaqCategory(title=cat_title, order_index=order_idx)
        db.add(cat)
        db.flush()
        for item_order, (q, a) in enumerate(items):
            item = models.FaqItem(
                category_id=cat.id,
                question=q,
                answer=a,
                order_index=item_order,
            )
            db.add(item)

    db.commit()
    print("✅ FAQ 및 약관 초기 데이터 삽입 완료")


if __name__ == "__main__":
    db = SessionLocal()
    try:
        run_migration(db)
    finally:
        db.close()
